CREATE DATABASE IF NOT EXISTS diet_recommendation_db;
USE diet_recommendation_db;

-- Single table holding the complete pre-loaded patient report.
-- Populated once via scripts/seed_database.py from dataset/patients_500_dataset.csv.
-- The web app only ever READS from this table by patient_id — no new
-- registrations, no live CNN calls during normal use.
CREATE TABLE IF NOT EXISTS patients (
    patient_id        VARCHAR(10) PRIMARY KEY,
    full_name         VARCHAR(100) NOT NULL,
    age               INT,
    gender            VARCHAR(10),
    height_cm         FLOAT,
    weight_kg         FLOAT,
    bmi               FLOAT,
    glucose_mg        INT,
    blood_pressure    VARCHAR(10),
    insulin_mu        INT,
    activity_level    VARCHAR(20),
    retina_image      VARCHAR(150),   -- filename only, served from static/retina_images/
    dr_stage          VARCHAR(30),    -- No DR / Mild DR / Moderate DR / Severe DR / Proliferative DR
    dr_severity       VARCHAR(30),    -- Low Risk / Medium Risk / High Risk / Very High Risk
    confidence        FLOAT,          -- CNN model confidence %, genuine output of diabetes_model.h5
    calories_kcal     INT,
    protein_g         INT,
    carbs_g           INT,
    fat_g             INT,
    diet_plan         TEXT,           -- semicolon-separated sample meal items
    recommendation    TEXT,           -- short final recommendation line
    detailed_guidance TEXT            -- longer detailed control guidance
);
CREATE TABLE IF NOT EXISTS food_items (
    id           INT AUTO_INCREMENT PRIMARY KEY,
    food_name    VARCHAR(150),
    meal_type    VARCHAR(20),
    calories     FLOAT,
    carbs_g      FLOAT,
    protein_g    FLOAT,
    fat_g        FLOAT,
    suitable_for VARCHAR(20),
    cuisine      VARCHAR(30)
);

